import test from "node:test";
import assert from "node:assert/strict";
import {
  createMavlinkDecoder,
  createMavlinkMonitor,
} from "../shared/mavlink-telemetry.js";
import { mavlinkPacket, telemetryPackets } from "./fixtures/mavlink.mjs";

test("MAVLink receive-only monitor handles v1/v2 framing, CRC, source isolation and aging", () => {
  const monitor = createMavlinkMonitor();
  let now = 1000;
  const push = createMavlinkDecoder((frame) => monitor.receive(frame, now));
  assert.equal(monitor.snapshot(now).state, "waiting");
  const corrupt = mavlinkPacket(0, [0, 0, 0, 0, 2, 3, 0, 3, 3]);
  corrupt[corrupt.length - 1] ^= 1;
  push(corrupt);
  assert.equal(monitor.snapshot(now).state, "waiting");
  for (const frame of telemetryPackets({ version: 1 })) {
    push(frame.slice(0, 3));
    push(frame.slice(3));
  }
  const value = monitor.snapshot(now);
  assert.equal(value.state, "ready");
  assert.equal(value.vehicle, "PX4");
  assert.equal(value.system, 17);
  assert.equal(value.position.longitude, 27.5005);
  assert.equal(value.position.latitude, 38.5005);
  assert.equal(value.position.altitudeMslM, 160);
  assert.equal(value.position.altitudeAboveHomeM, 35);
  assert.equal(value.position.groundSpeedMps, 5);
  assert.equal(value.position.headingDegrees, 270);
  assert.equal(value.batteryPercent, 72);
  assert.equal(value.mission.sequence, 7);
  assert.equal(value.mission.state, null);

  now = 2000;
  push(telemetryPackets({ system: 54 })[0]);
  push(mavlinkPacket(42, [8, 0, 10, 0, 3], { signed: true }));
  assert.equal(monitor.snapshot(now).mission.state, "Etkin");
  assert.equal(monitor.snapshot(now).mission.sequence, 8);
  assert.equal(monitor.snapshot(now).system, 17);
  assert.equal(monitor.snapshot(6000).state, "stale");
  assert.equal(monitor.snapshot(6000).position, null);
});

test("unsupported links stay offline and truncated zero extension is decoded", () => {
  const monitor = createMavlinkMonitor(),
    now = 1000;
  const push = createMavlinkDecoder((frame) => monitor.receive(frame, now));
  push(mavlinkPacket(0, [0, 0, 0, 0, 6, 8, 0, 3, 3]));
  assert.equal(monitor.snapshot(now).state, "waiting");
  push(mavlinkPacket(0, [0, 0, 0, 0, 2, 3, 0, 3, 3]));
  push(mavlinkPacket(42, [1]));
  push(mavlinkPacket(1, new Uint8Array(30)));
  assert.equal(monitor.snapshot(now).vehicle, "ArduPilot");
  assert.equal(monitor.snapshot(now).mission.sequence, 1);
  assert.equal(monitor.snapshot(now).batteryPercent, 0);
});

test("reference PyMAVLink common dialect packets decode without local fixture encoding", () => {
  const now = 1000,
    monitor = createMavlinkMonitor();
  const push = createMavlinkDecoder((frame) => monitor.receive(frame, now));
  // Generated by PyMAVLink 2.4.50 with a synthetic PX4 system and position.
  for (const bytes of [
    "fd09000000110100000000000000020c0003035793",
    "fd1c000000110121000000000000c8b5f216483e641000710200b88800002c019001000078699e67",
    "fd1f00000011010100000000000000000000000000000000ffffffff00000000000000000000000048c055",
    "fd0600000011012a000007000c000301b2a8",
  ])
    push(Buffer.from(bytes, "hex"));
  const sample = monitor.snapshot(now);
  assert.equal(sample.vehicle, "PX4");
  assert.equal(sample.position.altitudeAboveHomeM, 35);
  assert.equal(sample.batteryPercent, 72);
  assert.equal(sample.mission.state, "Etkin");
});
